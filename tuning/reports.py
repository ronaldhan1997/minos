"""Phase reports built only from stored trial records."""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

from tuning.storage import atomic_json, read_json


def trial_records(run_dir: Path, phase: int) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    root = run_dir / "trials"
    if not root.is_dir():
        return rows
    for path in sorted(root.glob("*/trial.json")):
        row = json.loads(path.read_text(encoding="utf-8"))
        if row.get("phase") == phase:
            rows.append(row)
    rows.sort(key=lambda row: row.get("trial", 0))
    return rows


def successful(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [row for row in rows if row.get("objective") is not None]


def write_phase_report(run_dir: Path, phase: int, manifest: dict[str, Any]) -> dict[str, Any]:
    rows = trial_records(run_dir, phase)
    ranked = sorted(successful(rows), key=lambda row: row["objective"], reverse=True)
    best = ranked[0] if ranked else None
    summary = {
        "phase": phase,
        "trials_recorded": len(rows),
        "successful_trials": len(ranked),
        "failed_trials": len(rows) - len(ranked),
        "best_objective": None if best is None else best["objective"],
        "best_config_sha256": None if best is None else best.get("config_sha256"),
        "best_trial": None if best is None else best.get("trial"),
        "scoring_version": manifest["scoring_version"],
        "robustness_penalty": manifest["robustness_penalty"],
        "train_samples": manifest["train_samples"],
        "single_sample_exploratory": manifest.get("single_sample_exploratory", False),
        "objective": manifest["objective"],
    }
    phase_dir = run_dir / f"phase{phase}"
    phase_dir.mkdir(parents=True, exist_ok=True)
    atomic_json(phase_dir / f"phase{phase}_summary.json", summary)
    if best is not None:
        from tuning.baseline import write_conf

        write_conf(phase_dir / f"phase{phase}_best.conf", best["parameters"])
    _write_top_csv(phase_dir / f"phase{phase}_top10.csv", ranked[:10])
    (phase_dir / f"phase{phase}_report.md").write_text(_markdown(summary, ranked[:10]), encoding="utf-8")
    if phase == 1:
        _write_shortlist(run_dir, ranked)
    if phase == 2:
        _write_finalists(run_dir, ranked, manifest)
    return summary


def _write_top_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["rank", "trial", "objective", "config_sha256", "status"],
        )
        writer.writeheader()
        for rank, row in enumerate(rows, start=1):
            writer.writerow(
                {
                    "rank": rank,
                    "trial": row.get("trial"),
                    "objective": row.get("objective"),
                    "config_sha256": row.get("config_sha256"),
                    "status": row.get("status"),
                }
            )


def _write_shortlist(run_dir: Path, ranked: list[dict[str, Any]]) -> None:
    seen: set[str] = set()
    shortlist = []
    for row in ranked:
        digest = row.get("config_sha256")
        if not digest or digest in seen:
            continue
        seen.add(digest)
        shortlist.append({"trial": row.get("trial"), "objective": row["objective"], "config_sha256": digest})
        if len(shortlist) >= 8:
            break
    atomic_json(run_dir / "phase1" / "shortlist.json", {"configs": shortlist})


def _write_finalists(run_dir: Path, ranked: list[dict[str, Any]], manifest: dict[str, Any]) -> None:
    seen: set[str] = set()
    finalists = []
    for row in ranked[:10]:
        digest = row.get("config_sha256")
        if not digest or digest in seen:
            continue
        seen.add(digest)
        finalists.append(
            {
                "trial": row.get("trial"),
                "objective": row["objective"],
                "config_sha256": digest,
                "parameters": row["parameters"],
                "train_samples": manifest["train_samples"],
            }
        )
    atomic_json(
        run_dir / "finalists_manifest.json",
        {
            "source": "phase2_training_only",
            "scoring_version": manifest["scoring_version"],
            "finalists": finalists,
            "note": "Frozen before held-out validation. Do not edit this file from validation scores.",
        },
    )


def _markdown(summary: dict[str, Any], top: list[dict[str, Any]]) -> str:
    lines = [
        f"# Phase {summary['phase']} report",
        "",
        f"Scoring version: `{summary['scoring_version']}`",
        f"Objective: `{summary['objective']}`",
        f"Robustness penalty: {summary['robustness_penalty']}",
        f"Recorded trials: {summary['trials_recorded']}",
        f"Successful trials: {summary['successful_trials']}",
        f"Failed trials: {summary['failed_trials']}",
        f"Best objective: {summary['best_objective']}",
        "",
    ]
    if summary.get("single_sample_exploratory"):
        lines.extend(
            [
                "This run used one training sample. The number is a single-sample",
                "exploratory result. It does not estimate performance on other samples.",
                "",
            ]
        )
    lines.append("Top trials")
    lines.append("")
    for row in top:
        lines.append(f"- trial {row.get('trial')}: objective {row.get('objective')} `{row.get('config_sha256')}`")
    if not top:
        lines.append("- none yet")
    lines.append("")
    return "\n".join(lines)


def load_summary(run_dir: Path, phase: int) -> dict[str, Any]:
    return read_json(run_dir / f"phase{phase}" / f"phase{phase}_summary.json")
